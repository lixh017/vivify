export type Catalog = Record<TranslationKey, string>

// Locale display labels for the switcher. Deliberately kept here (not
// in the catalog) because the user is selecting the locale itself —
// we need to know what to render regardless of which locale is
// currently active. If you wanted to localize these too you'd need
// to know the *target* locale the user is about to switch to, which
// requires additional UI structure. Out of scope for Phase 1.
export const LOCALE_LABELS: Record<Locale, string> = {
  zh: '中',
  en: 'EN',
}

// Cookie attribute constants. Centralised so middleware, the API
// route, and the client-side switcher all set the same values. A
// 1-year maxAge keeps the user's pick across sessions; SameSite=Lax
// covers the normal navigation flow without leaking the cookie to
// cross-site subresources. We do NOT set Secure in dev because
// http://localhost would drop the cookie — the production deploy
// sits behind HTTPS so the browser treats it as secure-by-default.
export const LOCALE_COOKIE_MAX_AGE = 60 * 60 * 24 * 365
export const LOCALE_COOKIE_PATH = '/'
